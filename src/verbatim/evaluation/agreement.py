"""Agreement between two labelling passes over the same questions.

The second pass is labelled blind, from a template that holds only the questions, after a
break. Agreement is measured before the passes are reconciled.
"""

import random
from collections import Counter
from dataclasses import dataclass
from typing import Any

from verbatim.evaluation.testset import Question


def cohen_kappa(first: list[str], second: list[str]) -> float | None:
    """Agreement corrected for chance. None if chance agreement is already 1."""
    if len(first) != len(second) or not first:
        raise ValueError("both passes need the same, non-zero number of labels")
    n = len(first)
    observed = sum(a == b for a, b in zip(first, second, strict=True)) / n
    counts_first, counts_second = Counter(first), Counter(second)
    expected = sum(counts_first[label] * counts_second[label] for label in counts_first) / n**2
    if expected == 1:
        return None
    return (observed - expected) / (1 - expected)


def jaccard(first: set[str], second: set[str]) -> float:
    if not first and not second:
        return 1.0
    return len(first & second) / len(first | second)


@dataclass(frozen=True, slots=True)
class Difference:
    id: str
    field: str
    first: str
    second: str


@dataclass(frozen=True, slots=True)
class Agreement:
    n: int
    category_agreement: float
    category_kappa: float | None
    answerable_agreement: float
    answerable_kappa: float | None
    as_of_agreement: float
    refs_exact: float
    refs_jaccard: float
    answer_points_first: int
    answer_points_second: int
    differences: tuple[Difference, ...]


def _refs(q: Question) -> set[str]:
    return {str(ref) for ref in q.gold_refs}


def compare(first: list[Question], second: list[Question]) -> Agreement:
    by_id = {q.id: q for q in second}
    if sorted(by_id) != sorted(q.id for q in first) or len(by_id) != len(second):
        raise ValueError("both passes must contain the same question ids, each once")
    pairs = [(a, by_id[a.id]) for a in sorted(first, key=lambda q: q.id)]
    for a, b in pairs:
        if a.question != b.question:
            raise ValueError(f"{a.id}: question text differs between the passes")

    n = len(pairs)
    differences: list[Difference] = []
    for a, b in pairs:
        for field, x, y in [
            ("category", a.category, b.category),
            ("answerable", str(a.answerable), str(b.answerable)),
            ("as_of", a.as_of, b.as_of),
            ("gold_refs", ", ".join(sorted(_refs(a))), ", ".join(sorted(_refs(b)))),
        ]:
            if x != y:
                differences.append(Difference(a.id, field, x, y))

    def share(field: str) -> float:
        return 1 - sum(d.field == field for d in differences) / n

    return Agreement(
        n=n,
        category_agreement=share("category"),
        category_kappa=cohen_kappa([a.category for a, _ in pairs], [b.category for _, b in pairs]),
        answerable_agreement=share("answerable"),
        answerable_kappa=cohen_kappa(
            [str(a.answerable) for a, _ in pairs], [str(b.answerable) for _, b in pairs]
        ),
        as_of_agreement=share("as_of"),
        refs_exact=share("gold_refs"),
        refs_jaccard=sum(jaccard(_refs(a), _refs(b)) for a, b in pairs) / n,
        answer_points_first=sum(len(a.answer_points) for a, _ in pairs),
        answer_points_second=sum(len(b.answer_points) for _, b in pairs),
        differences=tuple(differences),
    )


def _kappa(value: float | None) -> str:
    return "n/a (one label only)" if value is None else f"{value:.2f}"


def render_markdown(result: Agreement) -> str:
    lines = [
        "# Labelling agreement",
        "",
        "Generated by `make agreement` from `eval/testset/labeling/pass1.jsonl` and",
        "`pass2.jsonl`. Do not edit by hand.",
        "",
        f"Questions: {result.n}",
        "",
        "| Field | Agreement | Cohen's kappa |",
        "| --- | --- | --- |",
        f"| Category | {result.category_agreement:.0%} | {_kappa(result.category_kappa)} |",
        f"| Answerable | {result.answerable_agreement:.0%} | {_kappa(result.answerable_kappa)} |",
        f"| As-of date | {result.as_of_agreement:.0%} | |",
        f"| Gold references, identical sets | {result.refs_exact:.0%} | |",
        f"| Gold references, mean Jaccard | {result.refs_jaccard:.2f} | |",
        "",
        f"Answer points: {result.answer_points_first} in pass 1, "
        f"{result.answer_points_second} in pass 2. They are free text and are compared by hand "
        "while reconciling.",
        "",
        "## Differences",
        "",
    ]
    if not result.differences:
        lines.append("None.")
    else:
        lines += ["| Question | Field | Pass 1 | Pass 2 |", "| --- | --- | --- | --- |"]
        lines += [f"| {d.id} | {d.field} | {d.first} | {d.second} |" for d in result.differences]
    return "\n".join(lines) + "\n"


def blank_template(questions: list[Question], seed: int) -> list[dict[str, Any]]:
    """The questions of pass 1 without any labels, shuffled, for a blind second pass."""
    template: list[dict[str, Any]] = [
        {
            "id": q.id,
            "question": q.question,
            "category": "",
            "answerable": None,
            "as_of": "",
            "gold_refs": [],
            "answer_points": [],
            "notes": "",
        }
        for q in questions
    ]
    random.Random(seed).shuffle(template)
    return template
