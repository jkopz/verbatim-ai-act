from dataclasses import replace

import pytest

from verbatim.evaluation.agreement import (
    blank_template,
    cohen_kappa,
    compare,
    jaccard,
    render_markdown,
)
from verbatim.evaluation.testset import GoldRef, Question


def _q(id: str, **changes: object) -> Question:
    q = Question(
        id=id,
        question=f"Question {id}?",
        category="fact_lookup",
        answerable=True,
        as_of="2026-11-27",
        gold_refs=(GoldRef("ai-act", "Art. 5"),),
        answer_points=("point",),
        notes="",
    )
    return replace(q, **changes)  # pyright: ignore[reportArgumentType]


def test_cohen_kappa_textbook_example() -> None:
    # 50 items, observed agreement 0.7, expected 0.5 -> kappa 0.4
    a = ["yes"] * 25 + ["no"] * 25
    b = ["yes"] * 20 + ["no"] * 5 + ["yes"] * 10 + ["no"] * 15
    assert cohen_kappa(a, b) == pytest.approx(0.4)


def test_cohen_kappa_perfect_and_undefined() -> None:
    assert cohen_kappa(["a", "b"], ["a", "b"]) == 1.0
    # Both passes used a single label: chance agreement is 1, kappa is undefined.
    assert cohen_kappa(["a", "a"], ["a", "a"]) is None


def test_jaccard() -> None:
    assert jaccard({"x", "y"}, {"y", "z"}) == pytest.approx(1 / 3)
    assert jaccard(set[str](), set[str]()) == 1.0


def test_compare_counts_agreement_and_lists_differences() -> None:
    first = [_q("q1"), _q("q2"), _q("q3"), _q("q4")]
    second = [
        _q("q1"),
        _q("q2", category="definition"),
        _q("q3", gold_refs=(GoldRef("ai-act", "Art. 5"), GoldRef("ai-act", "Art. 6"))),
        _q("q4", as_of="2026-01-01"),
    ]
    result = compare(first, second)
    assert result.n == 4
    assert result.category_agreement == 0.75
    assert result.answerable_agreement == 1.0
    assert result.as_of_agreement == 0.75
    assert result.refs_exact == 0.75
    assert result.refs_jaccard == pytest.approx((1 + 1 + 0.5 + 1) / 4)
    assert [(d.id, d.field) for d in result.differences] == [
        ("q2", "category"),
        ("q3", "gold_refs"),
        ("q4", "as_of"),
    ]


def test_compare_ignores_order_but_requires_the_same_questions() -> None:
    assert compare([_q("q1"), _q("q2")], [_q("q2"), _q("q1")]).n == 2
    with pytest.raises(ValueError, match="same question ids"):
        compare([_q("q1")], [_q("q2")])
    with pytest.raises(ValueError, match="q1: question text differs"):
        compare([_q("q1")], [_q("q1", question="Changed?")])


def test_render_markdown_marks_the_file_as_generated() -> None:
    text = render_markdown(compare([_q("q1")], [_q("q1")]))
    assert text.startswith("# Labelling agreement")
    assert "Generated by `make agreement`" in text


def test_blank_template_keeps_only_id_and_question_in_a_fixed_shuffled_order() -> None:
    questions = [_q(f"q{i}") for i in range(10)]
    template = blank_template(questions, seed=1)
    assert template == blank_template(questions, seed=1)
    assert sorted(t["id"] for t in template) == sorted(q.id for q in questions)
    assert [t["id"] for t in template] != [q.id for q in questions]
    assert template[0] == {
        "id": template[0]["id"],
        "question": f"Question {template[0]['id']}?",
        "category": "",
        "answerable": None,
        "as_of": "",
        "gold_refs": [],
        "answer_points": [],
        "notes": "",
    }
